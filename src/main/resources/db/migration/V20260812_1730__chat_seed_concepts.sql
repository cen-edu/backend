-- 3. 적재 검증 ----------------------------------------------------------------
-- 기대값과 다르면 예외를 던져 이 마이그레이션을 실패시킨다.
-- Flyway 가 롤백하므로 절반만 적재된 상태가 남지 않는다.
DO $$
DECLARE
    n_concept  INTEGER;
    n_prereq   INTEGER;
    n_mid      INTEGER;
    n_elem     INTEGER;
    n_bad_mid  INTEGER;
    n_bad_elem INTEGER;
BEGIN
    SELECT COUNT(*) INTO n_concept FROM chat_concept;
    SELECT COUNT(*) INTO n_prereq  FROM chat_concept_prereq;
    SELECT COUNT(*) INTO n_mid  FROM chat_concept WHERE grade_band = 'MIDDLE_1';
    SELECT COUNT(*) INTO n_elem FROM chat_concept WHERE grade_band = 'ELEMENTARY';
    SELECT COUNT(*) INTO n_bad_mid  FROM chat_concept
        WHERE grade_band = 'MIDDLE_1'   AND sub_unit_id IS NULL;
    SELECT COUNT(*) INTO n_bad_elem FROM chat_concept
        WHERE grade_band = 'ELEMENTARY' AND sub_unit_id IS NOT NULL;

    IF n_concept <> 455 THEN
        RAISE EXCEPTION '개념 행 수가 455가 아니다: %', n_concept;
    END IF;
    IF n_prereq <> 1098 THEN
        RAISE EXCEPTION '선수관계 행 수가 1098이 아니다: %', n_prereq;
    END IF;
    IF n_mid <> 210 OR n_elem <> 245 THEN
        RAISE EXCEPTION '학년대 분포가 다르다: 중1 % / 초등 %', n_mid, n_elem;
    END IF;
    IF n_bad_mid <> 0 THEN
        RAISE EXCEPTION '소단원이 붙지 않은 중1 개념이 있다: %건. external_key 대조 실패', n_bad_mid;
    END IF;
    IF n_bad_elem <> 0 THEN
        RAISE EXCEPTION '소단원이 붙은 초등 개념이 있다: %건', n_bad_elem;
    END IF;

    RAISE NOTICE '개념 % 행 / 선수관계 % 행 적재 완료 (중1 % / 초등 %)',
        n_concept, n_prereq, n_mid, n_elem;
END $$;
