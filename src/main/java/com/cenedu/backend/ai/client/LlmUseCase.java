package com.cenedu.backend.ai.client;

/**
 * 호출 목적. 목적별로 모델·추론 강도·응답 상한을 다르게 설정하기 위한 설정 키다.
 *
 * <p><b>문제 저작과 검증이 같은 모델이면 안 된다.</b> 같은 모델은 같은 방식으로 틀리고, 둘 다 틀려도
 * 대조는 통과한다. 그러면 검증기가 통과 도장 기계가 된다. 모델을 가르는 지점이 필요해서 이 enum 이 있다.
 *
 * <p>enum 상수 이름이 곧 {@code app.ai.client.use-cases.*} 의 키다. 문자열 키로 두지 않은 이유는
 * 오타가 조용히 기본값으로 흘러가기 때문이다 — 검증이 저작과 같은 모델로 돌아도 아무 표시가 없다.
 */
public enum LlmUseCase {

    /** 목적을 지정하지 않은 호출. {@code app.ai.client} 최상위 설정을 그대로 쓴다. */
    DEFAULT,

    /** 생성·수정된 문제 후보의 독립 검증. 저작측과 다른 모델을 써야 한다. */
    VERIFICATION
}
