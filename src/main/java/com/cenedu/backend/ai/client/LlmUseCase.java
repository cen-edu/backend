package com.cenedu.backend.ai.client;

/**
 * 호출 목적. 목적별로 모델·추론 강도·응답 상한을 다르게 설정하기 위한 설정 키다.
 *
 * <p><b>문제 저작과 검증이 같은 모델이면 안 된다.</b> 같은 모델은 같은 방식으로 틀리고, 둘 다 틀려도
 * 대조는 통과한다. 그러면 검증기가 통과 도장 기계가 된다. 모델을 가르는 지점이 필요해서 이 enum 이 있다.
 *
 * <p>enum 상수 이름이 곧 {@code app.ai.client.use-cases.*} 의 키다. 문자열 키로 두지 않은 이유는
 * 오타가 조용히 기본값으로 흘러가기 때문이다 — 검증이 저작과 같은 모델로 돌아도 아무 표시가 없다.
 */
public enum LlmUseCase {

    /** 목적을 지정하지 않은 호출. {@code app.ai.client} 최상위 설정을 그대로 쓴다. */
    DEFAULT,

    /** 생성·수정된 문제 후보의 독립 검증. 저작측과 다른 모델을 써야 한다. */
    VERIFICATION,

    /**
     * 학생 분석 문장 생성. 모델은 기본값과 같고 <b>응답 상한만 다르다</b>.
     *
     * <p>한 번의 호출로 문항마다 문장 세 개씩을 받는다. 실측으로 문항당 약 110 토큰이라
     * 25문항 근처에서 기본 상한 3000 에 닿고, 넘으면 JSON 이 잘려 보고서가 통째로 실패한다.
     * 종합평가가 20~30문항이라 기본값으로는 감당되지 않는다.
     */
    ANALYSIS_REPORT,

    /**
     * 개념 챗봇의 도구 루프. <b>모델을 고정한다.</b>
     *
     * <p>도구 선택·턴 수·앵커 유지를 측정으로 맞춰 놓은 경로라, 기본 모델이 다른 작업의 판단으로
     * 바뀌면 그 측정이 통째로 무효가 된다. 실제로 기본값이 {@code gpt-5-mini} 에서 바뀌면서
     * 도구를 싣는 호출이 400 을 받았다.
     */
    CONCEPT_CHAT_LOOP,

    /**
     * 서술형 채점의 도구 루프. 어느 모델로 채점할지를 <b>지금 재고 있는 중</b>이라 설정으로 뺀다.
     *
     * <p>도구를 싣는 경로라 모델과 추론 강도를 함께 봐야 한다 — 둘을 따로 고를 수 없는 모델이 있다.
     */
    ESSAY_GRADING
}
