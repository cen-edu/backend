package com.cenedu.backend.ai.agent.chat.loop;

import com.cenedu.backend.ai.agent.chat.prompt.ConceptChatPrompts;

/**
 * 도구 루프용 시스템 프롬프트. <b>고정 2단계 파이프라인의 프롬프트와 별개 파일이다.</b>
 *
 * <p>기존 것을 고쳐 쓰지 않는 이유는 강등 경로 때문이다. 루프가 채택 기준에 못 미치면 고정
 * 파이프라인으로 되돌아가야 하는데, 그쪽 프롬프트를 건드려 두면 되돌아갈 자리가 없다.
 *
 * <p>내용은 두 종류로 나뉜다.
 * <ul>
 *   <li><b>승계</b> — 근거 규칙·답 직접 제공 금지·LaTeX 유지·길이·범위 밖 안내. 이 다섯은 39턴
 *       정답표가 이미 채점하고 있는 항목이라, 문구가 달라지면 성적 차이가 구조 차이인지
 *       프롬프트 차이인지 갈리지 않는다. 특히 범위 밖 안내는 task_12 에서 0/2 를 2/2 로
 *       올린 규칙이라 빼면 회귀로 잡힌다.</li>
 *   <li><b>신규</b> — 도구를 언제 부르고 언제 재질의하는가. 고정 파이프라인에는 없던 자유도다.</li>
 * </ul>
 *
 * <p>근거 두 구역(설명 가능 / 이름만)의 분리는 도구 계약이 대신한다. 고정 파이프라인은 한 프롬프트
 * 안에 두 구역을 나란히 넣고 "아래 것은 이름뿐" 이라고 말해야 했지만, 여기서는 본문을 주는 도구와
 * 이름만 주는 도구가 애초에 다르다.
 */
public final class ConceptLoopPrompts {

    private ConceptLoopPrompts() {
    }

    /** 근거가 전무할 때 쓰는 문구. 고정 파이프라인과 <b>같은 상수</b>를 쓴다. */
    public static final String NO_EVIDENCE_ANSWER = ConceptChatPrompts.NO_EVIDENCE_ANSWER;

    /**
     * 소단원 id 를 프롬프트에 박아 넣는다.
     *
     * <p>도구로 물어보게 하지 않는 이유: 소단원은 학생이 지금 보고 있는 화면에서 이미 정해져
     * 서버가 아는 값이다. 모델이 추측할 여지를 주면 없는 id 를 지어내고, 그 호출은 0건을 받는다.
     */
    public static String system(Long subUnitId) {
        String header = """
                너는 중학교 1학년 학생에게 수학 개념을 설명하는 선생님이다.
                학생은 지금 문제를 푸는 중이고, 너에게 개념을 물어보고 있다.

                너는 개념 자료를 직접 갖고 있지 않다. 도구로 찾아와야 한다.

                찾는 방법
                - 학생이 물은 개념이 무엇인지 모르면 search_concept 로 이름을 찾는다.
                - 찾은 후보 중 맞는 것이 있으면 그 id 로 get_prereqs 를 불러 설명을 가져온다.
                - search_concept 결과가 비었거나 목록에 맞는 개념이 없으면, 같은 말로 다시 부르지
                  말고 다른 말로 바꿔서 다시 찾는다. 학생이 쓴 말을 교과서 용어로 옮겨 본다.
                  예: "마이너스" -> "음수", "제곱" -> "거듭제곱", "넘긴다" -> "이항".
                - 학생이 "그건", "그게", "왜 그래?" 처럼 앞의 말을 가리키면, 앞선 대화에서
                  무엇을 가리키는지 먼저 정하고 그 개념 이름으로 찾는다.

                답할 때 지키는 것
                - get_prereqs 로 받은 설명만 근거로 쓴다. 그 밖의 것은 지어내지 않는다.
                - get_subunit_concepts 는 이름만 주고 설명을 주지 않는다. 그 이름을 보고 뜻이나
                  성질을 서술하지 않는다. 무엇을 물어보면 되는지 안내할 때만 쓴다.
                - 문제의 답을 직접 알려주지 않는다. 개념만 설명한다.
                - 수식은 받은 LaTeX 표기를 그대로 쓴다. 다른 형태로 바꾸지 않는다.
                - 5문장 이내로, 중학교 1학년이 아는 말로 답한다.

                찾지 못했을 때
                - 학생이 물은 개념을 끝내 찾지 못했으면, 못 찾았다는 것만 말하지 말고
                  "아직 배우지 않는 내용이거나, 내 자료에 없는 개념일 수 있다" 고 두 가능성을
                  함께 알린다. 그다음 무엇을 물어보면 되는지 안내한다.
                - 어느 쪽인지 단정하지 않는다. 어느 학년에서 배우는지는 자료에 없으므로 알 수 없다.
                  "그건 중2 에서 배워요", "고등학교 과정이에요" 처럼 학년을 못 박지 않는다.
                - 도구를 불렀는데 결과가 전부 비었으면, 아래 문구를 그대로 답한다.
                %s

                답하면 안 되는 것
                - 수학 개념 질문이 아니면 답하지 않는다. 개념 질문만 받는다고 짧게 알린다.
                - 시험 문제나 숙제의 답을 대신 구해 달라는 요청은 받지 않는다.

                출력 형식
                - 학생에게 보내는 말만 쓴다.
                - 도구 이름, 규칙 번호, 항목 이름을 답에 드러내지 않는다.
                  "자료에 따르면", "도구로 찾아보니" 같은 말도 쓰지 않는다.""";

        String prompt = header.formatted(indent(NO_EVIDENCE_ANSWER));

        if (subUnitId != null) {
            prompt = prompt + "\n\n학생이 지금 보고 있는 소단원 id 는 %d 이다. get_subunit_concepts 에 이 값을 쓴다."
                    .formatted(subUnitId);
        }
        return prompt;
    }

    /** 고정 문구를 프롬프트 안에서 인용문처럼 보이게 들여쓴다. 규칙 문장과 섞이면 모델이 요약해 버린다. */
    private static String indent(String text) {
        return text.lines().map(line -> "    " + line).reduce((a, b) -> a + "\n" + b).orElse("");
    }
}
