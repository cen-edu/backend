package com.cenedu.backend.ai.agent;

/**
 * 에이전트 식별자. {@link Agent#kind()} 가 돌려주는 값이며 디스패처가 이 값으로 구현체를 찾는다.
 *
 * <p>도메인 코드는 아래 자기 도메인 블록 <b>끝에</b> 추가한다. 블록을 지켜야 머지 충돌이 줄어든다.
 *
 * <p>지금 있는 세 개는 프론트 화면 기준으로 잡은 임시값이다. 에이전트를 어떻게 쪼갤지는
 * 아직 정하지 않았으므로, 실제 구현을 시작할 때 각자 블록에서 자유롭게 나누거나 합친다.
 */
public enum AgentKind {

    // ===== 공통/개발용 (이동규) =====
    /**
     * {@code local} 프로파일 전용 에코. 받은 요청을 그대로 돌려준다.
     *
     * <p>실제 에이전트가 나오기 전에 성공 경로를 밟아보려고 둔 값이라 아무도 진짜 구현을 만들지 않는다.
     * 세 서피스 중 하나를 빌려 쓰면, 그 서피스의 진짜 구현체가 생기는 순간 담당이 둘이 되어
     * 그 사람 로컬에서 앱이 기동하지 않는다. 배포 프로파일에는 구현체가 없어
     * {@code AI_AGENT_NOT_FOUND} 가 난다.
     */
    ECHO,

    // ===== problem (이하영) =====
    /** 문제 3종 생성 결과 화면의 AI 수정 (문제·풀이 단계·개념 설명·정답·채점 기준). */
    PROBLEM_EDIT,

    // ===== chat (배세빈) =====
    /** 학생이 문제를 푸는 중에 쓰는 챗봇. */
    SOLVE_CHAT,
    /** 채점 결과·해설 화면에서 쓰는 챗봇. */
    REVIEW_CHAT,

    // ===== grading (배세빈) =====

    // ===== analysis (모수환) =====
    ;
}
