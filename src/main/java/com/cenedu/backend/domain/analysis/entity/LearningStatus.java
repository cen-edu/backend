package com.cenedu.backend.domain.analysis.entity;

/**
 * 학생의 한 풀이 단계에 대한 상태.
 *
 * <p>판정 범위는 문제지 한 회분이다. 문제지 하나에서 관찰한 것으로 그 회분의 상태를 정하고,
 * 다음 회분은 다음 문제지로 다시 정한다. 세 단계를 시간에 걸쳐 올라가는 모델이 아니다.
 */
public enum LearningStatus {

    /** 그 단계에서 오류가 관찰되지 않았다. 이 회분에서 확인할 것이 없다. */
    CLEAR,

    /** 오류가 관찰됐지만 지원 기준에는 못 미친다. */
    WATCH,

    /** 그 단계 문항의 절반 이상을 서로 다른 문항에서 틀렸다. */
    NEEDS_SUPPORT,

    /**
     * 지도 후 힌트 없이 연속으로 해결했다.
     *
     * <p>{@link #NEEDS_SUPPORT} 를 거친 뒤 다시 3회를 맞혀야 하므로 한 회분 문제지 안에서는
     * 나오지 않는다. 여러 회분을 함께 넣을 때만 나온다.
     */
    IMPROVED
}
